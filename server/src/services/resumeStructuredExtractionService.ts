export const extractStructuredResume =
  async ({
    resumeText,
    rawResumeText,
    layoutPages,
  }: StructuredResumeExtractionParams): Promise<StructuredResumeExtractionResult> => {
    const cleanedResumeText =
      cleanText(
        resumeText
      );

    const cleanedRawResumeText =
      cleanText(
        rawResumeText ||
        ""
      );

    if (
      !cleanedResumeText &&
      !cleanedRawResumeText
    ) {
      throw new Error(
        "Resume text is required for structured extraction."
      );
    }

    console.log(
      "[Structured Resume] Deterministic extraction START"
    );

    const startedAt =
      Date.now();

    const usingLayout =
      hasUsableMultiColumnLayout(
        layoutPages
      );

    const reconstructedProfile =
      buildDeterministicProfile(
        cleanedResumeText ||
        cleanedRawResumeText
      );

    const rawProfile =
      cleanedRawResumeText
        ? buildDeterministicProfile(
            cleanedRawResumeText
          )
        : undefined;

    const layoutProfile =
      usingLayout
        ? buildLayoutAwareProfile(
            cleanedResumeText ||
              cleanedRawResumeText,
            layoutPages
          )
        : undefined;

    const selection =
      chooseBestStructuredProfile({
        rawCandidate:
          rawProfile,

        reconstructedCandidate:
          reconstructedProfile,

        layoutCandidate:
          layoutProfile,
      });

    const profile =
      selection.profile;

    const selectedMode =
      selection.mode;

    const selectedText =
      selectedMode ===
        "raw-text"
        ? cleanedRawResumeText
        : cleanedResumeText ||
          cleanedRawResumeText;

    console.log(
      "[Structured Resume] Candidate comparison",
      {
        detectedMultiColumn:
          usingLayout,

        raw:
          rawProfile
            ? getProfileDiagnosticSummary(
                rawProfile
              )
            : null,

        reconstructed:
          getProfileDiagnosticSummary(
            reconstructedProfile
          ),

        layout:
          layoutProfile
            ? getProfileDiagnosticSummary(
                layoutProfile
              )
            : null,

        selected:
          selectedMode,
      }
    );

    const warnings =
      uniqueStrings(
        profile
          .extractionWarnings
      );

    const elapsedMs =
      Date.now() -
      startedAt;

    console.log(
      "[Structured Resume] Deterministic extraction COMPLETE",
      {
        elapsedMs,

        mode:
          selectedMode,

        detectedMultiColumn:
          usingLayout,

        profileQuality:
          getProfileCompletenessScore(
            profile
          ),

        status:
          profile
            .extractionStatus,

        fullName:
          profile
            .contact
            .fullName,

        experienceCount:
          profile
            .experience
            .length,

        projectCount:
          profile
            .projects
            .length,

        educationCount:
          profile
            .education
            .length,

        certificationCount:
          profile
            .certifications
            .length,

        volunteeringCount:
          profile
            .volunteering
            .length,

        hackathonCount:
          profile
            .hackathons
            .length,

        skillCount:
          profile
            .skills
            .length,

        technicalSkillCount:
          profile
            .technicalSkills
            .length,

        softSkillCount:
          profile
            .softSkills
            .length,

        languageCount:
          profile
            .languages
            .length,

        rawSectionCount:
          profile
            .rawSections
            .length,

        warningCount:
          warnings.length,
      }
    );

    return {
      profile,

      /*
       * Backward-compatible field. There is no model anymore.
       */
      rawModelText:
        JSON.stringify(
          profile
        ),

      success:
        true,

      warnings,

      selectedText,

      selectedMode,
    };
  };

/* =========================================================
   DEFAULT EXPORT
========================================================= */

export default {
  extractStructuredResume,
};
