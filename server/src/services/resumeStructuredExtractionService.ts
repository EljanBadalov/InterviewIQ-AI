const parseVolunteering = (
  lines: string[],
  warnings: string[]
): IStructuredResumeVolunteering[] => {
  const blocks =
    buildDatedBlocks(
      lines
    );

  const result:
    IStructuredResumeVolunteering[] = [];

  blocks.forEach(
    (
      block,
      index
    ) => {
      const contentLines =
        block.lines
          .filter(
            Boolean
          )
          .filter(
            (
              line
            ) =>
              !isPageArtifact(
                line
              )
          );

      if (
        contentLines.length ===
        0
      ) {
        return;
      }

      const heading =
        stripBulletPrefix(
          contentLines[0] ||
          ""
        );

      const split =
        splitRoleAndOrganization(
          heading
        );

      const body =
        contentLines.slice(
          1
        );

      const bullets =
        body
          .filter(
            isBulletLine
          )
          .map(
            stripBulletPrefix
          );

      const description =
        body
          .filter(
            (
              line
            ) =>
              !isBulletLine(
                line
              )
          )
          .map(
            stripBulletPrefix
          )
          .filter(
            Boolean
          )
          .join(
            " "
          );

      if (
        !split.organization
      ) {
        warnings.push(
          `Volunteering ${index + 1} organization could not be separated confidently from the source heading. User review is recommended.`
        );
      }

      result.push({
        organization:
          split.organization,

        role:
          split.role,

        location:
          "",

        startDate:
          block.date
            ?.startDate ||
          "",

        endDate:
          block.date
            ?.endDate ||
          "",

        isCurrent:
          block.date
            ?.isCurrent ||
          false,

        description:
          cleanText(
            description
          ),

        bullets:
          uniqueStrings(
            bullets
          ),
      });
    }
  );

  return result;
};

