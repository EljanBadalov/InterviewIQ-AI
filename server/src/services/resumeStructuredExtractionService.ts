const looksLikeSkillsList = (
  value: string
): boolean => {
  const cleaned =
    cleanSingleLineText(
      value
    );

  if (!cleaned) {
    return false;
  }

  const lower =
    cleaned
      .toLowerCase();

  if (
    lower.startsWith(
      "programming languages:"
    ) ||
    lower.startsWith(
      "technical skills:"
    ) ||
    lower.startsWith(
      "frameworks:"
    ) ||
    lower.startsWith(
      "frameworks & libraries:"
    ) ||
    lower.startsWith(
      "developer tools:"
    ) ||
    lower.startsWith(
      "skills:"
    )
  ) {
    return true;
  }

  const commas =
    (
      cleaned.match(
        /,/g
      ) ||
      []
    ).length;

  return (
    commas >=
      4 &&
    /\b(?:javascript|typescript|react|html|css|python|java|node|bootstrap|tailwind|git|github|mongodb|sql|express)\b/i.test(
      cleaned
    )
  );
};

const looksLikeDateOnly = (
  value: string
): boolean => {
  const cleaned =
    cleanSingleLineText(
      value
    );

  if (!cleaned) {
    return false;
  }

  if (
    /^(?:19|20)\d{2}$/i.test(
      cleaned
    )
  ) {
    return true;
  }

  const date =
    findDateRange(
      cleaned
    );

  return Boolean(
    date &&
    normalizeComparableText(
      cleanSingleLineText(
        date.matchedText
      )
    ) ===
      normalizeComparableText(
        cleaned
      )
  );
};

const looksLikeSectionHeading = (
  value: string
): boolean => {
  return Boolean(
    detectSectionKey(
      value
    )
  );
};

