/* =========================================================
   DETERMINISTIC SOURCE GROUNDING

   Even though this service no longer uses an AI model, the
   grounding layer stays as a final safety check and guarantees
   that extracted factual strings originate from source text.
========================================================= */

const normalizeForGrounding = (
  value: string
): string => {
  return cleanText(
    value
  )
    .toLowerCase()
    .replace(
      /[•●▪◦·]/g,
      " "
    )
    .replace(
      /[–—−]/g,
      "-"
    )
    .replace(
      /[“”]/g,
      '"'
    )
    .replace(
      /[‘’]/g,
      "'"
    )
    .replace(
      /\s+/g,
      " "
    )
    .trim();
};

const isGroundedInResumeText = (
  value: string,
  resumeText: string
): boolean => {
  const candidate =
    normalizeForGrounding(
      value
    );

  if (!candidate) {
    return true;
  }

  const source =
    normalizeForGrounding(
      resumeText
    );

  if (
    source.includes(
      candidate
    )
  ) {
    return true;
  }

  const tokens =
    candidate
      .split(
        /[^a-z0-9+#.]+/i
      )
      .map(
        (
          token
        ) =>
          token.trim()
      )
      .filter(
        (
          token
        ) =>
          token.length >=
          2
      );

  if (
    tokens.length ===
    0
  ) {
    return false;
  }

  if (
    tokens.length <=
    6
  ) {
    return tokens.every(
      (
        token
      ) =>
        source.includes(
          token
        )
    );
  }

  return false;
};

const keepGroundedString = (
  value: string,
  resumeText: string,
  fieldPath: string,
  warnings: string[]
): string => {
  const cleaned =
    cleanText(
      value
    );

  if (!cleaned) {
    return "";
  }

  if (
    isGroundedInResumeText(
      cleaned,
      resumeText
    )
  ) {
    return cleaned;
  }

  warnings.push(
    `${fieldPath} could not be verified directly against the source resume text and was removed. User confirmation may be required.`
  );

  return "";
};

const keepGroundedSingleLine = (
  value: string,
  resumeText: string,
  fieldPath: string,
  warnings: string[]
): string => {
  return cleanSingleLineText(
    keepGroundedString(
      value,
      resumeText,
      fieldPath,
      warnings
    )
  );
};

const keepGroundedList = (
  values: string[],
  resumeText: string,
  fieldPath: string,
  warnings: string[]
): string[] => {
  return values.filter(
    (
      value,
      index
    ) => {
      if (
        isGroundedInResumeText(
          value,
          resumeText
        )
      ) {
        return true;
      }

      warnings.push(
        `${fieldPath}[${index}] could not be verified directly against the source resume text and was removed.`
      );

      return false;
    }
  );
};

