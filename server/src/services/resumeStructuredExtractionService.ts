const inferCertificationStatusFromSource = (
  value: string
): StructuredCertificationStatus => {
  const normalized =
    normalizeComparableText(
      value
    );

  if (
    /expired|müddəti bitib|muddeti bitib/i.test(
      normalized
    )
  ) {
    return "expired";
  }

  if (
    /in progress|ongoing|currently studying|preparing|expected|hazırda|hazirda|davam edir/i.test(
      normalized
    )
  ) {
    return "in-progress";
  }

  return "unknown";
};

const parseCertifications = (
  lines: string[]
): IStructuredResumeCertification[] => {
  const sourceLines =
    lines
      .map(
        cleanSingleLineText
      )
      .filter(
        Boolean
      )
      .filter(
        (
          line
        ) =>
          !isPageArtifact(
            line
          )
      );

  interface ICertBlock {
    heading: string;
    date: IDateRange | null;
    details: string[];
  }

  const looksLikeTrainingProvider = (
    value: string
  ): boolean => {
    const cleaned =
      cleanSingleLineText(
        value
      );

    if (!cleaned) {
      return false;
    }

    return /\b(?:school|academy|college|university|institute|institut|bootcamp|course|training|technest|holberton|coursera|edx|udemy|freecodecamp|odin project|məktəb|mekteb|akademiya|kollec|universitet|təlim|telim)\b/i.test(
      cleaned
    );
  };

  const blocks:
    ICertBlock[] = [];

  let current:
    ICertBlock | null =
      null;

  const pushCurrent = (): void => {
    if (
      current &&
      current.heading
    ) {
      blocks.push({
        heading:
          current.heading,

        date:
          current.date,

        details:
          [...current.details],
      });
    }

    current = null;
  };

  for (
    const rawLine
    of sourceLines
  ) {
    const date =
      findDateRange(
        rawLine
      );

    const withoutDate =
      date
        ? removeDateText(
            rawLine,
            date
          )
        : rawLine;

    const cleaned =
      stripBulletPrefix(
        withoutDate
      );

    /*
     * IMPORTANT:
     * Training sections often use:
     *
     *   Holberton School Azerbaijan Baku
     *   Computer Science (Web Development) - Scholarship Recipient  2025
     *
     * The second line is NOT a new certification. It is the program
     * belonging to the provider above.
     */
    if (
      date &&
      cleaned &&
      current &&
      !current.date &&
      looksLikeTrainingProvider(
        current.heading
      )
    ) {
      current.details.push(
        cleaned
      );

      current.date =
        date;

      continue;
    }

    /*
     * Date + text normally starts a new independent certificate when
     * there is no open provider waiting for its program.
     */
    if (
      date &&
      cleaned
    ) {
      pushCurrent();

      current = {
        heading:
          cleaned,

        date,

        details:
          [],
      };

      continue;
    }

    /*
     * Standalone date belongs only to the currently open item.
     */
    if (
      date &&
      !cleaned
    ) {
      if (current) {
        current.date =
          date;
      }

      continue;
    }

    if (!cleaned) {
      continue;
    }

    /*
     * Once a dated item is complete, the next non-bullet line starts
     * the next provider/certificate.
     */
    if (
      current &&
      current.date &&
      !isBulletLine(
        rawLine
      )
    ) {
      pushCurrent();

      current = {
        heading:
          cleaned,

        date:
          null,

        details:
          [],
      };

      continue;
    }

    if (!current) {
      current = {
        heading:
          cleaned,

        date:
          null,

        details:
          [],
      };

      continue;
    }

    /*
     * Before the date appears, following lines belong to the current
     * provider as program/field/details.
     */
    current.details.push(
      cleaned
    );
  }

  pushCurrent();

  const allSourceDates =
    sourceLines
      .map(
        (
          line
        ) =>
          findDateRange(
            line
          )
      )
      .filter(
        (
          value
        ): value is IDateRange =>
          Boolean(
            value
          )
      )
      .map(
        (
          value
        ) => ({
          startDate:
            value.startDate,

          endDate:
            value.endDate,
        })
      );

  const usedDateKeys =
    new Set<string>(
      blocks
        .filter(
          (
            block
          ) =>
            Boolean(
              block.date
            )
        )
        .map(
          (
            block
          ) =>
            `${block.date?.startDate || ""}|${block.date?.endDate || ""}`
        )
    );

  const unusedSourceDates =
    allSourceDates.filter(
      (
        date
      ) =>
        !usedDateKeys.has(
          `${date.startDate}|${date.endDate}`
        )
    );

  let recoveryIndex =
    0;

  return blocks.map(
    (
      block
    ) => {
      const pipeParts =
        splitPipeSeparated(
          block.heading
        );

      const rawName =
        pipeParts[0] ||
        block.heading;

      const providerParts =
        splitTrailingLocationFromOrganization(
          rawName
        );

      const name =
        providerParts.location
          ? `${providerParts.name} (${providerParts.location})`
          : providerParts.name;

      const explicitIssuer =
        pipeParts.length >
          1
          ? pipeParts
              .slice(
                1
              )
              .join(
                " | "
              )
          : "";

      const programDetail =
        block.details.find(
          (
            item
          ) =>
            !URL_RE.test(
              item
            ) &&
            !/credential\s+id/i.test(
              item
            )
        ) ||
        "";

      const issuer =
        explicitIssuer ||
        programDetail;

      const fullText =
        block.details.join(
          " "
        );

      const credentialUrl =
        fullText.match(
          URL_RE
        )?.[0] ||
        "";

      const credentialId =
        fullText.match(
          /credential\s+id\s*[:#-]?\s*([A-Za-z0-9._-]+)/i
        )?.[1] ||
        "";

      let issueDate =
        block.date
          ?.startDate ||
        "";

      let expirationDate =
        block.date
          ?.endDate ||
        "";

      /*
       * Recover only an explicit unused date from the same
       * Training/Certifications source section. No year is invented.
       */
      if (
        !issueDate &&
        recoveryIndex <
        unusedSourceDates.length
      ) {
        const recovered =
          unusedSourceDates[
            recoveryIndex
          ];

        recoveryIndex +=
          1;

        issueDate =
          recovered
            ?.startDate ||
          "";

        expirationDate =
          recovered
            ?.endDate ||
          "";
      }

      return {
        name:
          cleanSingleLineText(
            name
          ),

        issuer:
          cleanSingleLineText(
            issuer
          ),

        issueDate:
          cleanSingleLineText(
            issueDate
          ),

        expirationDate:
          cleanSingleLineText(
            expirationDate
          ),

        credentialId:
          cleanSingleLineText(
            credentialId
          ),

        credentialUrl:
          cleanSingleLineText(
            credentialUrl
          ),

        status:
          inferCertificationStatusFromSource(
            [
              block.heading,
              ...block.details,
            ].join(
              " "
            )
          ),
      };
    }
  );
};

/* =========================================================
   LANGUAGES
========================================================= */

const parseLanguageToken = (
  value: string
): IStructuredResumeLanguage | null => {
  const cleaned =
    stripBulletPrefix(
      value
    );

  if (!cleaned) {
    return null;
  }

  if (
    /programming\s+languages?/i.test(
      cleaned
    )
  ) {
    return null;
  }

  const colonIndex =
    cleaned.indexOf(
      ":"
    );

  if (
    colonIndex >
      0
  ) {
    return {
      language:
        cleanSingleLineText(
          cleaned.slice(
            0,
            colonIndex
          )
        ),

      level:
        cleanSingleLineText(
          cleaned.slice(
            colonIndex +
              1
          )
        ),
    };
  }

  const parenthetical =
    cleaned.match(
      /^(.+?)\s*\((.+)\)$/
    );

  if (
    parenthetical
  ) {
    return {
      language:
        cleanSingleLineText(
          parenthetical[1] ||
          ""
        ),

      level:
        cleanSingleLineText(
          parenthetical[2] ||
          ""
        ),
    };
  }

  const cefrMatch =
    cleaned.match(
      /^(.+?)\s+(A1|A2|B1|B2|C1|C2)$/i
    );

  if (
    cefrMatch
  ) {
    return {
      language:
        cleanSingleLineText(
          cefrMatch[1] ||
          ""
        ),

      level:
        cleanSingleLineText(
          cefrMatch[2] ||
          ""
        ).toUpperCase(),
    };
  }

  const dashMatch =
    cleaned.match(
      /^(.+?)\s*[-–—]\s*(.+)$/
    );

  if (
    dashMatch
  ) {
    return {
      language:
        cleanSingleLineText(
          dashMatch[1] ||
          ""
        ),

      level:
        cleanSingleLineText(
          dashMatch[2] ||
          ""
        ),
    };
  }

  return {
    language:
      cleaned,

    level:
      "",
  };
};

const parseLanguages = (
  lines: string[]
): IStructuredResumeLanguage[] => {
  const tokens =
    lines
      .flatMap(
        (
          line
        ) => {
          const cleaned =
            cleanSingleLineText(
              line
            );

          if (!cleaned) {
            return [];
          }

          /*
           * "Azerbaijani (Native), Turkish (...), English (...)"
           */
          return cleaned
            .split(
              /,(?=\s*[A-Za-zÀ-ÖØ-öø-ÿƏəĞğÇçŞşİıÖöÜü])/u
            )
            .map(
              (
                item
              ) =>
                item.trim()
            )
            .filter(
              Boolean
            );
        }
      );

  const result:
    IStructuredResumeLanguage[] = [];

  for (
    const token
    of tokens
  ) {
    const parsed =
      parseLanguageToken(
        token
      );

    if (
      parsed &&
      parsed.language
    ) {
      result.push(
        parsed
      );
    }
  }

  const seen =
    new Set<string>();

  return result.filter(
    (
      item
    ) => {
      const key =
        `${item.language.toLowerCase()}|${item.level.toLowerCase()}`;

      if (
        seen.has(
          key
        )
      ) {
        return false;
      }

      seen.add(
        key
      );

      return true;
    }
  );
};

