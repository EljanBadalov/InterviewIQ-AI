const parseListLines = (
  lines: string[]
): string[] => {
  const result:
    string[] = [];

  for (
    const line
    of lines
  ) {
    const cleaned =
      stripBulletPrefix(
        line
      );

    if (!cleaned) {
      continue;
    }

    /*
     * Keep labelled lines intact if they describe a category.
     * The skill parser handles those separately.
     */
    if (
      cleaned.includes(
        ":"
      )
    ) {
      result.push(
        cleaned
      );

      continue;
    }

    if (
      /[,;]/.test(
        cleaned
      )
    ) {
      result.push(
        ...splitCommaSeparated(
          cleaned
        )
      );

      continue;
    }

    result.push(
      cleaned
    );
  }

  return uniqueStrings(
    result
  );
};

const looksLikeSkillCategoryLine = (
  value: string
): boolean => {
  const cleaned =
    stripBulletPrefix(
      value
    );

  if (!cleaned) {
    return false;
  }

  return /^(?:programming languages?|frameworks?(?:\s*&\s*libraries)?|libraries|developer tools?|tools|databases?|technical skills?|frontend|backend|technologies?)\s*:/i.test(
    cleaned
  );
};

const parseGlobalSkillCategoryLines = (
  lines: string[]
): string[] => {
  const values:
    string[] = [];

  for (
    const line
    of lines
  ) {
    if (
      !looksLikeSkillCategoryLine(
        line
      )
    ) {
      continue;
    }

    const cleaned =
      stripBulletPrefix(
        line
      );

    const colonIndex =
      cleaned.indexOf(
        ":"
      );

    if (
      colonIndex < 0
    ) {
      continue;
    }

    values.push(
      ...splitCommaSeparated(
        cleaned.slice(
          colonIndex + 1
        )
      )
    );
  }

  return uniqueStrings(
    values
  );
};

const parseSkillsSection = (
  lines: string[]
): {
  skills: string[];
  technicalSkills: string[];
} => {
  const skills:
    string[] = [];

  const technicalSkills:
    string[] = [];

  for (
    const rawLine
    of lines
  ) {
    const line =
      stripBulletPrefix(
        rawLine
      );

    if (!line) {
      continue;
    }

    const colonIndex =
      line.indexOf(
        ":"
      );

    if (
      colonIndex >
      0
    ) {
      const label =
        line
          .slice(
            0,
            colonIndex
          )
          .trim()
          .toLowerCase();

      const value =
        line
          .slice(
            colonIndex +
              1
          )
          .trim();

      const items =
        splitCommaSeparated(
          value
        );

      if (
        /programming|language|framework|library|libraries|database|tool|technology|technologies|frontend|backend|devops|cloud|api/i.test(
          label
        )
      ) {
        technicalSkills.push(
          ...items
        );
      } else {
        skills.push(
          ...items
        );
      }

      continue;
    }

    const items =
      /[,;]/.test(
        line
      )
        ? splitCommaSeparated(
            line
          )
        : [
            line,
          ];

    technicalSkills.push(
      ...items
    );
  }

  return {
    skills:
      uniqueStrings(
        skills
      ),

    technicalSkills:
      uniqueStrings(
        technicalSkills
      ),
  };
};

/* =========================================================
   DATED BLOCK PARSER
========================================================= */

const buildDatedBlocks = (
  lines: string[]
): IDatedBlock[] => {
  const cleanedLines =
    lines
      .map(
        (
          line
        ) =>
          cleanSingleLineText(
            line
          )
      )
      .filter(
        Boolean
      )
      .filter(
        (
          line
        ) =>
          !isPageArtifact(
            line
          )
      );

  if (
    cleanedLines.length ===
    0
  ) {
    return [];
  }

  /*
   * Deterministic entry segmentation.
   *
   * Resume sections commonly use one of these layouts:
   *
   *   Title — Company          Jan 2024 - Present
   *   Description...
   *
   * or
   *
   *   Title — Company
   *   Jan 2024 - Present
   *   Description...
   *
   * Every explicit date line/token starts a new entry. If the date
   * is on its own line, the immediately preceding non-bullet line is
   * moved into the new entry as its heading.
   *
   * This prevents a description from the previous entry becoming the
   * title of the next Experience / Volunteering / Education /
   * Certification record.
   */
  const blocks:
    IDatedBlock[] = [];

  let current:
    IDatedBlock | null =
      null;

  const pushCurrent = (): void => {
    if (
      !current ||
      current.lines.length ===
        0
    ) {
      current = null;

      return;
    }

    blocks.push({
      lines:
        [...current.lines],

      date:
        current.date,
    });

    current = null;
  };

  const startBlock = (
    heading: string,
    date:
      IDateRange
  ): void => {
    pushCurrent();

    current = {
      lines:
        heading
          ? [heading]
          : [],

      date,
    };
  };

  for (
    let index = 0;
    index <
    cleanedLines.length;
    index +=
      1
  ) {
    const line =
      cleanedLines[
        index
      ] ||
      "";

    const date =
      findDateRange(
        line
      );

    if (
      date
    ) {
      const withoutDate =
        removeDateText(
          line,
          date
        );

      /*
       * Date and heading are on the same source line.
       */
      if (
        withoutDate
      ) {
        startBlock(
          withoutDate,
          date
        );

        continue;
      }

      /*
       * Standalone date line. Prefer the immediately previous
       * non-bullet line as the heading for this dated entry.
       */
      let recoveredHeading =
        "";

      if (
        current &&
        current.lines.length >
          0
      ) {
        const lastIndex =
          current.lines.length -
          1;

        const previous =
          current.lines[
            lastIndex
          ] ||
          "";

        if (
          previous &&
          !isBulletLine(
            previous
          ) &&
          !looksLikeSkillCategoryLine(
            previous
          )
        ) {
          recoveredHeading =
            previous;

          current.lines.splice(
            lastIndex,
            1
          );

          if (
            current.lines.length >
              0
          ) {
            pushCurrent();
          } else {
            current = null;
          }
        } else {
          pushCurrent();
        }
      } else {
        pushCurrent();
      }

      current = {
        lines:
          recoveredHeading
            ? [
                recoveredHeading,
              ]
            : [],

        date,
      };

      continue;
    }

    if (!current) {
      current = {
        lines:
          [],

        date:
          null,
      };
    }

    current.lines.push(
      line
    );
  }

  pushCurrent();

  return blocks.filter(
    (
      block
    ) =>
      block.lines.length >
      0
  );
};


/* =========================================================
   HEADING PARSING
========================================================= */

const splitRoleAndOrganization = (
  value: string
): {
  role: string;
  organization: string;
} => {
  const cleaned =
    cleanSingleLineText(
      value
    );

  if (!cleaned) {
    return {
      role:
        "",
      organization:
        "",
    };
  }

  /*
   * Prefer explicit dash / pipe separators because these are the
   * most common resume heading forms:
   *   Front-End Developer — DigitCodex
   *   Volunteer | RIIB
   */
  const explicitSeparators = [
    /\s+[—–-]\s+/,
    /\s+\|\s+/,
    /\s+\bat\b\s+/i,
  ];

  for (
    const separator
    of explicitSeparators
  ) {
    const parts =
      cleaned
        .split(
          separator
        )
        .map(
          (
            part
          ) =>
            part.trim()
        )
        .filter(
          Boolean
        );

    if (
      parts.length >=
        2
    ) {
      return {
        role:
          parts[0] ||
          "",

        organization:
          parts
            .slice(
              1
            )
            .join(
              " — "
            ),
      };
    }
  }

  /*
   * Comma separation is used only when the first part clearly looks
   * like a role. This avoids splitting organization names that
   * legitimately contain commas.
   */
  const commaParts =
    cleaned
      .split(
        /\s*,\s*/
      )
      .filter(
        Boolean
      );

  if (
    commaParts.length >=
      2
  ) {
    const first =
      commaParts[0] ||
      "";

    const firstLower =
      first.toLowerCase();

    if (
      KNOWN_ROLE_WORDS.some(
        (
          word
        ) =>
          firstLower.includes(
            word
          )
      )
    ) {
      return {
        role:
          first,

        organization:
          commaParts
            .slice(
              1
            )
            .join(
              ", "
            ),
      };
    }
  }

  return {
    role:
      cleaned,

    organization:
      "",
  };
};

const splitProjectHeading = (
  value: string
): {
  name: string;
  technologies: string[];
} => {
  const parts =
    splitPipeSeparated(
      value
    );

  if (
    parts.length ===
    0
  ) {
    return {
      name:
        cleanSingleLineText(
          value
        ),

      technologies:
        [],
    };
  }

  const name =
    parts[0] ||
    "";

  const technologies =
    parts
      .slice(
        1
      )
      .flatMap(
        (
          part
        ) =>
          splitCommaSeparated(
            part
          )
      );

  return {
    name:
      cleanSingleLineText(
        name
      ),

    technologies:
      uniqueStrings(
        technologies
      ),
  };
};

