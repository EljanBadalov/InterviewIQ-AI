const buildDeterministicProfile = (
  resumeText: string
): IStructuredResumeProfile => {
  const warnings:
    string[] = [];

  const lines =
    buildCleanLines(
      resumeText
    );

  const sections =
    splitIntoDetectedSections(
      lines
    );

  const preambleLines =
    getSectionLines(
      sections,
      "preamble"
    );

  const technicalSkillLines =
    getSectionLines(
      sections,
      "technicalSkills"
    );

  const coreSkillLines =
    getSectionLines(
      sections,
      "coreSkills"
    );

  const softSkillLines =
    getSectionLines(
      sections,
      "softSkills"
    );

  const technicalSkillResult =
    parseSkillsSection(
      technicalSkillLines
    );

  const coreSkillResult =
    parseSkillsSection(
      coreSkillLines
    );

  /*
   * PDF text extraction can occasionally lose a section heading
   * while preserving category rows such as:
   * "Programming Languages: JavaScript, Python"
   * "Frameworks & Libraries: React.js, Next.js"
   *
   * Recover only the explicit values written after those labels.
   * No inference is performed.
   */
  const globallyLabelledTechnicalSkills =
    parseGlobalSkillCategoryLines(
      lines
    );

  const professionalSummary =
    cleanText(
      getSectionLines(
        sections,
        "professionalSummary"
      ).join(
        " "
      )
    );

  const experienceLines =
    getSectionLines(
      sections,
      "experience"
    );

  const projectLines =
    getSectionLines(
      sections,
      "projects"
    );

  const educationLines =
    getSectionLines(
      sections,
      "education"
    );

  const certificationLines =
    getSectionLines(
      sections,
      "certifications"
    );

  const languageLines =
    getSectionLines(
      sections,
      "languages"
    );

  const volunteeringLines =
    getSectionLines(
      sections,
      "volunteering"
    );

  const hackathonLines =
    getSectionLines(
      sections,
      "hackathons"
    );

  if (
    experienceLines.length ===
      0
  ) {
    warnings.push(
      "No explicit Experience section was detected. If the source CV contains employment history under a non-standard heading, user review is required."
    );
  }

  if (
    educationLines.length ===
      0
  ) {
    warnings.push(
      "No explicit Education section was detected."
    );
  }

  const profile:
    IStructuredResumeProfile = {
      contact:
        extractContact(
          preambleLines,
          lines,
          warnings
        ),

      professionalSummary,

      skills:
        uniqueStrings([
          ...technicalSkillResult
            .skills,

          ...coreSkillResult
            .skills,
        ]),

      technicalSkills:
        uniqueStrings([
          ...technicalSkillResult
            .technicalSkills,

          ...coreSkillResult
            .technicalSkills,

          ...globallyLabelledTechnicalSkills,
        ]),

      softSkills:
        uniqueStrings([
          ...parseListLines(
            softSkillLines
          ),
        ]),

      experience:
        parseExperience(
          experienceLines,
          warnings
        ),

      projects:
        parseProjects(
          projectLines,
          warnings
        ),

      education:
        parseEducation(
          educationLines,
          warnings
        ),

      certifications:
        parseCertifications(
          certificationLines
        ),

      languages:
        parseLanguages(
          languageLines
        ),

      volunteering:
        parseVolunteering(
          volunteeringLines,
          warnings
        ),

      hackathons:
        parseHackathons(
          hackathonLines
        ),

      achievements:
        parseListLines(
          getSectionLines(
            sections,
            "achievements"
          )
        ),

      interests:
        parseListLines(
          getSectionLines(
            sections,
            "interests"
          )
        ),

      rawSections:
        buildRawSections(
          sections,
          resumeText
        ),

      extractionStatus:
        "completed",

      extractionWarnings:
        [],
    };

  const sanityWarnings =
    buildSanityWarnings(
      profile
    );

  profile.extractionWarnings =
    uniqueStrings([
      ...warnings,
      ...sanityWarnings,
    ]);

  if (
    profile
      .extractionWarnings
      .length >
    0
  ) {
    profile.extractionStatus =
      "partial";
  }

  const sanitizedProfile =
    sanitizeStructuredProfileArtifacts(
      profile
    );

  return applyDeterministicSourceGrounding(
    sanitizedProfile,
    resumeText
  );
};

/* =========================================================
   PROFILE QUALITY SELECTION

   PDF column detection is probabilistic. A normal single-column CV can
   sometimes look multi-column because dates, bullets, or aligned labels
   create separate X clusters.

   To avoid destroying a good single-column parse, when multi-column
   layout is detected we build BOTH candidates:
     1) stable plain-text profile
     2) layout-aware profile

   Then we deterministically keep the profile that preserves more real
   resume information. This also works in the opposite direction:
   Canva/sidebar resumes normally score much better with the layout-aware
   candidate, so that candidate wins.
========================================================= */

const countProfileBullets = (
  profile:
    IStructuredResumeProfile
): number => {
  const experienceBullets =
    profile
      .experience
      .reduce(
        (
          total,
          item
        ) =>
          total +
          item
            .bullets
            .length,
        0
      );

  const projectBullets =
    profile
      .projects
      .reduce(
        (
          total,
          item
        ) =>
          total +
          item
            .bullets
            .length,
        0
      );

  const volunteerBullets =
    profile
      .volunteering
      .reduce(
        (
          total,
          item
        ) =>
          total +
          item
            .bullets
            .length,
        0
      );

  return (
    experienceBullets +
    projectBullets +
    volunteerBullets
  );
};

const getProfileCompletenessScore = (
  profile:
    IStructuredResumeProfile
): number => {
  let score =
    0;

  const contact =
    profile.contact;

  if (
    contact.fullName
  ) {
    score +=
      8;
  }

  if (
    contact.email
  ) {
    score +=
      4;
  }

  if (
    contact.phone
  ) {
    score +=
      3;
  }

  if (
    contact.linkedin ||
    contact.github ||
    contact.website
  ) {
    score +=
      2;
  }

  if (
    profile
      .professionalSummary
      .trim()
      .length >=
    40
  ) {
    score +=
      12;
  }

  score +=
    Math.min(
      profile
        .technicalSkills
        .length,
      12
    );

  score +=
    Math.min(
      profile
        .softSkills
        .length,
      6
    );

  score +=
    Math.min(
      profile
        .experience
        .length *
        10,
      40
    );

  score +=
    Math.min(
      profile
        .projects
        .length *
        9,
      36
    );

  score +=
    Math.min(
      profile
        .education
        .length *
        8,
      24
    );

  score +=
    Math.min(
      profile
        .certifications
        .length *
        5,
      20
    );

  score +=
    Math.min(
      profile
        .volunteering
        .length *
        5,
      20
    );

  score +=
    Math.min(
      profile
        .hackathons
        .length *
        4,
      12
    );

  score +=
    Math.min(
      profile
        .languages
        .length *
        3,
      12
    );

  score +=
    Math.min(
      countProfileBullets(
        profile
      ) *
        2,
      30
    );

  /*
   * A partial parse can still be useful, but it should lose a small
   * amount against a complete candidate with otherwise similar data.
   */
  if (
    profile
      .extractionStatus ===
      "partial"
  ) {
    score -=
      8;
  }

  score -=
    Math.min(
      profile
        .extractionWarnings
        .length *
        2,
      12
    );

  return score;
};

