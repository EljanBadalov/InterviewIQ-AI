const chooseBestStructuredProfile = ({
  rawCandidate,
  reconstructedCandidate,
  layoutCandidate,
}: {
  rawCandidate?:
    IStructuredResumeProfile;

  reconstructedCandidate:
    IStructuredResumeProfile;

  layoutCandidate?:
    IStructuredResumeProfile;
}): {
  profile:
    IStructuredResumeProfile;

  mode:
    | "raw-text"
    | "reconstructed-text"
    | "layout-aware";
} => {
  const candidates:
    Array<{
      mode:
        | "raw-text"
        | "reconstructed-text"
        | "layout-aware";

      profile:
        IStructuredResumeProfile;

      quality:
        number;
    }> = [];

  if (
    rawCandidate
  ) {
    candidates.push({
      mode:
        "raw-text",

      profile:
        rawCandidate,

      quality:
        getProfileCompletenessScore(
          rawCandidate
        ),
    });
  }

  candidates.push({
    mode:
      "reconstructed-text",

    profile:
      reconstructedCandidate,

    quality:
      getProfileCompletenessScore(
        reconstructedCandidate
      ),
  });

  if (
    layoutCandidate
  ) {
    candidates.push({
      mode:
        "layout-aware",

      profile:
        layoutCandidate,

      quality:
        getProfileCompletenessScore(
          layoutCandidate
        ),
    });
  }

  /*
   * Highest information-preservation score wins.
   *
   * Tie-breaking intentionally favors:
   *   raw-text > reconstructed-text > layout-aware
   *
   * because raw text is the least transformed representation and is
   * normally best for standard single-column ATS resumes.
   */
  const priority:
    Record<
      "raw-text" |
      "reconstructed-text" |
      "layout-aware",
      number
    > = {
      "raw-text":
        3,

      "reconstructed-text":
        2,

      "layout-aware":
        1,
    };

  candidates.sort(
    (
      a,
      b
    ) =>
      b.quality -
        a.quality ||
      priority[
        b.mode
      ] -
        priority[
          a.mode
        ]
  );

  const selected =
    candidates[0];

  if (!selected) {
    return {
      profile:
        reconstructedCandidate,

      mode:
        "reconstructed-text",
    };
  }

  return {
    profile:
      selected.profile,

    mode:
      selected.mode,
  };
};


