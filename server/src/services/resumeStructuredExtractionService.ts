/* =========================================================
   GENERIC HELPERS
========================================================= */

const cleanText = (
  value: unknown
): string => {
  if (
    typeof value !==
    "string"
  ) {
    return "";
  }

  return value
    .replace(
      /\u00a0/g,
      " "
    )
    .replace(
      /\r\n/g,
      "\n"
    )
    .replace(
      /\r/g,
      "\n"
    )
    .replace(
      /[ \t]+/g,
      " "
    )
    .replace(
      /\n{3,}/g,
      "\n\n"
    )
    .trim();
};

const cleanSingleLineText = (
  value: unknown
): string => {
  return cleanText(
    value
  )
    .replace(
      /\s+/g,
      " "
    )
    .trim();
};

const uniqueStrings = (
  values: unknown
): string[] => {
  if (
    !Array.isArray(
      values
    )
  ) {
    return [];
  }

  const seen =
    new Set<string>();

  const result:
    string[] = [];

  for (
    const value
    of values
  ) {
    const cleaned =
      cleanSingleLineText(
        value
      );

    if (!cleaned) {
      continue;
    }

    const key =
      cleaned
        .toLowerCase();

    if (
      seen.has(
        key
      )
    ) {
      continue;
    }

    seen.add(
      key
    );

    result.push(
      cleaned
    );
  }

  return result;
};

const isPageArtifact = (
  value: string
): boolean => {
  const cleaned =
    cleanSingleLineText(
      value
    );

  return PAGE_ARTIFACT_PATTERNS.some(
    (
      pattern
    ) =>
      pattern.test(
        cleaned
      )
  );
};

const stripBulletPrefix = (
  value: string
): string => {
  return cleanSingleLineText(
    value.replace(
      BULLET_PREFIX_RE,
      ""
    )
  );
};

const isBulletLine = (
  value: string
): boolean => {
  return BULLET_PREFIX_RE.test(
    value
  );
};

const normalizeHeadingText = (
  value: string
): string => {
  return cleanSingleLineText(
    value
  )
    .toLowerCase()
    .replace(
      /[:：]+$/u,
      ""
    )
    .replace(
      /[|]+$/g,
      ""
    )
    .trim();
};

const normalizeComparableText = (
  value: string
): string => {
  return cleanSingleLineText(
    value
  )
    .toLowerCase()
    .replace(
      /[–—−]/g,
      "-"
    )
    .replace(
      /[“”]/g,
      '"'
    )
    .replace(
      /[‘’]/g,
      "'"
    )
    .replace(
      /\s+/g,
      " "
    )
    .trim();
};

const splitCommaSeparated = (
  value: string
): string[] => {
  return uniqueStrings(
    cleanSingleLineText(
      value
    )
      .split(
        /\s*[,;]\s*/
      )
      .map(
        (
          item
        ) =>
          item.trim()
      )
  );
};

const splitPipeSeparated = (
  value: string
): string[] => {
  return uniqueStrings(
    cleanSingleLineText(
      value
    )
      .split(
        /\s*\|\s*/
      )
      .map(
        (
          item
        ) =>
          item.trim()
      )
  );
};

const removeSurroundingParentheses = (
  value: string
): string => {
  const cleaned =
    cleanSingleLineText(
      value
    );

  if (
    cleaned.startsWith(
      "("
    ) &&
    cleaned.endsWith(
      ")"
    )
  ) {
    return cleaned
      .slice(
        1,
        -1
      )
      .trim();
  }

  return cleaned;
};

const isCurrentText = (
  value: string
): boolean => {
  const normalized =
    normalizeComparableText(
      value
    );

  return CURRENT_TERMS.some(
    (
      term
    ) =>
      normalized.includes(
        normalizeComparableText(
          term
        )
      )
  );
};

/* =========================================================
   DATE EXTRACTION
========================================================= */

const findYearTokens = (
  value: string
): string[] => {
  return value.match(
    /\b(?:19|20)\d{2}\b/g
  ) || [];
};

const findDateRange = (
  value: string
): IDateRange | null => {
  const cleaned =
    cleanSingleLineText(
      value
    );

  if (!cleaned) {
    return null;
  }

  const monthToken =
    "(?:Jan(?:uary)?|Feb(?:ruary)?|Mar(?:ch)?|Apr(?:il)?|May|Jun(?:e)?|Jul(?:y)?|Aug(?:ust)?|Sep(?:t(?:ember)?)?|Oct(?:ober)?|Nov(?:ember)?|Dec(?:ember)?|Yanvar|Fevral|Mart|Aprel|May|İyun|Iyun|İyul|Iyul|Avqust|Sentyabr|Oktyabr|Noyabr|Dekabr)";

  const yearToken =
    "(?:19|20)\\d{2}";

  const datedToken =
    `(?:${monthToken}\\.?\\s+${yearToken}|${yearToken})`;

  const currentToken =
    "(?:Present|Current|Now|Ongoing|Today|Hazırda|Hazirda|Hazırkı vaxtadək|Hazirki vaxtadek|Davam edir|Devam edir|Indiyədək|Indiyedek)";

  const rangeRe =
    new RegExp(
      `(${datedToken})\\s*[-–—]\\s*(${datedToken}|${currentToken})`,
      "i"
    );

  const rangeMatch =
    cleaned.match(
      rangeRe
    );

  if (
    rangeMatch
  ) {
    const startDate =
      cleanSingleLineText(
        rangeMatch[1] ||
        ""
      );

    const endDate =
      cleanSingleLineText(
        rangeMatch[2] ||
        ""
      );

    return {
      startDate,
      endDate,
      isCurrent:
        isCurrentText(
          endDate
        ),
      matchedText:
        cleanSingleLineText(
          rangeMatch[0]
        ),
    };
  }

  /*
   * A single standalone month/year or year is useful for
   * projects, certificates, hackathons and education.
   * We intentionally match only the date token itself so
   * surrounding factual text is never consumed as a date.
   */
  const singleRe =
    new RegExp(
      `\\b(${datedToken})\\b`,
      "i"
    );

  const singleMatch =
    cleaned.match(
      singleRe
    );

  if (
    singleMatch
  ) {
    const token =
      cleanSingleLineText(
        singleMatch[1] ||
        ""
      );

    return {
      startDate:
        token,

      endDate:
        "",

      isCurrent:
        false,

      matchedText:
        token,
    };
  }

  return null;
};

const removeDateText = (
  value: string,
  date:
    IDateRange | null
): string => {
  if (
    !date ||
    !date.matchedText
  ) {
    return cleanSingleLineText(
      value
    );
  }

  return cleanSingleLineText(
    value
      .replace(
        date.matchedText,
        " "
      )
      .replace(
        /\(\s*\)/g,
        " "
      )
      .replace(
        /\[\s*\]/g,
        " "
      )
  );
};

/* =========================================================
   SECTION DETECTION
========================================================= */

const detectSectionKey = (
  value: string
): ResumeSectionKey | null => {
  const normalized =
    normalizeHeadingText(
      value
    );

  if (
    !normalized ||
    normalized.length >
      48
  ) {
    return null;
  }

  for (
    const definition
    of SECTION_ALIASES
  ) {
    if (
      definition.aliases.some(
        (
          alias
        ) =>
          normalized ===
          normalizeHeadingText(
            alias
          )
      )
    ) {
      return definition.key;
    }
  }

  return null;
};

